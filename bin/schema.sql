-- ================================================================ answers
-- One completed run of the agent, kept so the answer has a URL. /ask?q=... is
-- not that URL: it is an instruction to spend money and to sit through a fresh
-- run for a different answer.
--
-- What is kept is the answer and what it CITED, never the words it quoted. The
-- evidence is read back out of the archive when the page renders, so a redaction
-- or a corrected name applied since is already there. A reading that froze the
-- words would slowly disagree with the thing it claims to quote.
--
-- Passages are named by (video_id, start_idx, end_idx), not by id, because
-- index_passages reassigns ids on every rebuild. A range that stops resolving
-- means a redaction moved the boundaries, and the citation is then honestly gone
-- rather than quietly serving pre-redaction text. Agenda item ids ARE durable.
--
-- `answer` is generated prose quoting the transcript and cannot be reconstructed,
-- so it is the only copied text here and the only redaction surface. Nothing
-- deletes it: redact.py replaces the span in place, so a circulated link keeps
-- working and stops carrying the address.

-- The DO block below is a one-time correction and the only DROP in this file.
-- `answers` had a different shape for about an hour on 2026-08-14, and every
-- statement here is IF NOT EXISTS, so re-applying the schema over a dump from
-- that window would leave the dead shape in place. Guarded on a column only
-- that shape has. Delete it once no dump from before 2026-08-15 is in play.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'answers'
                 AND column_name = 'result') THEN
        RAISE NOTICE 'dropping the superseded `answers` table (it had `result`)';
        DROP TABLE answers;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS answers (
    -- Opaque, not a hash of the question: two runs of the same question can
    -- differ (the archive gains meetings, the model is not deterministic) and
    -- a permalink has to be the answer that was given, not the current one.
    id         text PRIMARY KEY,
    question   text NOT NULL,
    -- The prose, with its `[N]` and `[item:N]` markers intact. `cites.passages`
    -- carries the N each marker used, because those were passage ids at the
    -- time and will not be after the next rebuild - the render maps them back.
    answer     text NOT NULL,
    -- {"passages": [{"n": 220030, "video_id": ..., "start_idx": 0,
    --                "end_idx": 1}, ...],
    --  "items": [17923, ...]}
    cites      jsonb NOT NULL,
    -- What the run did, for the page that shows it: looked_at, struck,
    -- stopped, trace. Numbers and tool arguments, no archive text.
    run        jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
    -- `cites` has a shape, and it is asserted below rather than here. See the
    -- DO block: stating it in both places would be two definitions that can
    -- disagree, and a fresh database would then get a different constraint
    -- from an existing one.
);
-- The shape `cites` is READ as, asserted where it is written. Both keys are
-- addressed as arrays by bin/redact.py and bin/audit.py, and
-- jsonb_array_elements RAISES on anything else - so without this a malformed
-- row does not degrade a query, it turns applying a redaction into an error.
-- coalesce because a MISSING key yields SQL NULL and a CHECK passes on NULL:
-- "no passages key at all" has to fail too.
--
-- Stated HERE and not in the CREATE TABLE above, for two reasons. Written in
-- both places it would be two definitions that can disagree, and a fresh
-- database would get a different constraint from an existing one. And
-- CREATE TABLE IF NOT EXISTS does nothing at all when the table exists, so a
-- constraint written there alone never reaches any database but the first -
-- caught by adding it, re-running this file, and watching a malformed row
-- insert happily.
--
-- VALIDATED, and the first attempt at this was NOT VALID, which was wrong in a
-- way worth writing down. NOT VALID skips the rows already there but still
-- enforces every later INSERT *and UPDATE* - and the update that matters here
-- is redact.scrub_answers, taking an address out of an answer's prose. One
-- legacy malformed row would therefore turn "apply this redaction" into a
-- CheckViolation that rolls back the whole apply, archive-wide, until somebody
-- noticed. That is a worse failure than the malformed row.
--
-- So it validates: web/answers.py cannot write a row that fails this, so on any
-- real database the scan passes. If it ever does NOT, that is the finding, and
-- it surfaces while applying the schema - a deliberate act, at a keyboard -
-- rather than in the middle of removing somebody's address.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conname = 'answers_cites_shape'
                      AND conrelid = 'answers'::regclass) THEN
        ALTER TABLE answers ADD CONSTRAINT answers_cites_shape CHECK (
            coalesce(jsonb_typeof(cites -> 'passages'), 'missing') = 'array'
            AND coalesce(jsonb_typeof(cites -> 'items'), 'missing') = 'array');
    END IF;
END $$;

-- Answers that quote a given recording, which is the only way anything looks
-- this table up: bin/redact.py asks it once per span when a redaction is
-- applied. Measured over 5,000 answers - 10.1 ms expanding the jsonb per row,
-- 1.3 ms through this index, for 168 kB. jsonb_path_ops rather than the
-- default: it indexes only the containment operator, which is the only one
-- used here, and is smaller and faster for it.
CREATE INDEX IF NOT EXISTS answers_cited_video
    ON answers USING gin ((cites -> 'passages') jsonb_path_ops);
-- What has been asked, most recent first. For a person reading the queue, not
-- for expiry: nothing here expires (web/answers.py).
CREATE INDEX IF NOT EXISTS answers_recent ON answers (created_at DESC);

-- ------------------------------------------------------------------- asks
--
-- EVERY arrival at /api/ask, including the ones that were turned away. This
-- is the operator's table and no public route reads it. See web/asklog.py for
-- what `asker` is and why it is allowed to be NULL.
--
-- It exists because `answers` cannot answer the questions an operator has:
-- that table holds only the runs that SUCCEEDED, and holds nothing that
-- distinguishes one visitor from another, so "is anyone using this" and "how
-- much am I refusing" had no source at all. The two tables stay apart on
-- purpose rather than this being three more columns on `answers`. `answers`
-- is served to the public one row at a time by /ask/<id>; a column added
-- there is a column one careless SELECT away from being published, and the
-- whole point of `asker` is that it is never sent anywhere.
CREATE TABLE IF NOT EXISTS asks (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at        timestamptz NOT NULL DEFAULT now(),
    -- HMAC of the address and the local DATE, so it counts people within a
    -- day and cannot be joined across two. NULL means "not attributable"
    -- (no ASK_ASKER_KEY, or an address that was loopback because nothing was
    -- forwarding), which is deliberately NOT the same as one shared person:
    -- count(DISTINCT asker) skips NULLs, so a misconfigured day reads as
    -- questions with nobody behind them instead of one very busy visitor.
    asker     text,
    -- 'kept' - the run finished and was filed in `answers`.
    -- 'gone'  - the reader left mid-run. Paid for, nobody read it.
    -- 'error' - the run raised. The message is in the container log.
    -- everything else is limits.Throttled.kind: 'rate', 'daily', 'busy',
    -- 'closed', 'empty', 'length'.
    outcome   text NOT NULL,
    -- Set only when outcome = 'kept'. ON DELETE SET NULL because losing the
    -- prose must not lose the fact that somebody asked.
    answer_id text REFERENCES answers(id) ON DELETE SET NULL,
    chars     integer,
    -- Wall clock for a kept run. The one number that says whether the agent
    -- is getting slower, measured where a reader actually feels it.
    ms        integer,
    -- Truncated at 1,000. Refusals keep theirs too: the questions that got
    -- turned away are the ones that say whether the ceilings are right.
    question  text
);

-- Everything reads this table by time - a day, a week, the last hundred.
CREATE INDEX IF NOT EXISTS asks_recent ON asks (at DESC);

-- ---------------------------------------------------------------- subjects
--
-- What the county keeps coming back to, and the words it uses for each.
--
-- This replaces a literal in `web/archive.py`: eighteen subjects, each with a
-- hand-written regex over agenda titles and a hand-written tsquery over the
-- transcript. The measured failure is what moved it here. `affordable housing`
-- matched 23 published items. The SHIP program - the State Housing Initiatives
-- Partnership, which is how Florida funds affordable housing - is 66 more, and
-- the regex caught none of them; Community Development Block Grants are 129
-- more, and it caught one. The row read 23 where the subject is 304, and the
-- shape a reader saw was the pattern's, not the county's.
--
-- The fix is not to make the matching cleverer. It is to stop guessing the
-- vocabulary: a model proposes the phrases a Florida county actually uses, the
-- corpus grounds each one with a count and a real sample, and a person keeps or
-- drops it. Matching stays LEXICAL and stays here, which is what keeps these
-- counts on the record side of the two-truths rule:
-- counting published titles by phrase is exact and reproducible, where a
-- per-item model label or a cosine threshold would make every number on that
-- surface an inference and oblige it to be drawn as one.
CREATE TABLE IF NOT EXISTS subject (
    slug       text PRIMARY KEY,
    label      text NOT NULL,
    -- The /search query the row's title links to. Not derived from the terms:
    -- the strip counts titles that name the subject, and the link runs a
    -- ranked search over the whole archive, which is a different claim and
    -- says so.
    q          text NOT NULL,
    -- The model's own words for why it proposed this. Kept after curation on
    -- purpose: a subject list nobody can audit the provenance of is the thing
    -- this table exists to stop being.
    blurb      text,
    status     text NOT NULL DEFAULT 'proposed'
               CHECK (status IN ('proposed', 'kept', 'dropped')),
    -- Name and version of what proposed it, so one pass can be dropped and
    -- re-run by name the same reasoning, a level up from a fact.
    proposer   text,
    sort       integer,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- One phrase. `negative` excludes rather than includes, which the archive
-- genuinely needs: bare "license plate" takes in the county's spay/neuter
-- specialty-plate grant, and "flock" stems to the same token as investors
-- flocking into treasuries.
CREATE TABLE IF NOT EXISTS subject_term (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug     text NOT NULL REFERENCES subject(slug) ON DELETE CASCADE,
    phrase   text NOT NULL,
    negative boolean NOT NULL DEFAULT false,
    status   text NOT NULL DEFAULT 'proposed'
             CHECK (status IN ('proposed', 'kept', 'dropped')),
    -- GROUNDING, written when the phrase is proposed and never guessed. A
    -- reviewer decides on the count and the sample, not on the phrase alone -
    -- which is the whole difference between this and the regexes it replaces.
    -- `SHIP` as a substring matched 942 titles, most of them containing the
    -- word "township"; at a word boundary it matches 25. Nobody could have
    -- told those apart by reading the pattern.
    n_items      integer,
    n_utterances integer,
    sample       text,
    created_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (slug, phrase)
);

CREATE INDEX IF NOT EXISTS subject_term_live
    ON subject_term (slug) WHERE status = 'kept';

-- A subject may narrow into sub-subjects. Three of the twenty-seven derived
-- subjects are far larger than the rest - zoning and land use at 2,909 items,
-- development review at 2,408, community development districts at 2,109,
-- against 798 for the fourth - and a row that size stops answering the
-- question the strip asks. "Zoning and land use amendments" covers a rezoning
-- next door and a code text amendment in the same cell, and a resident does
-- not care about those equally.
--
-- Self-referencing rather than a second table: a sub-subject IS a subject -
-- same vocabulary, same grounding, same curation - and giving it its own
-- table would fork every one of those. Depth is one by construction, enforced
-- by the check below: a child of a child would render as a tree, and this is
-- a strip of years.
ALTER TABLE subject ADD COLUMN IF NOT EXISTS parent text
    REFERENCES subject(slug) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS subject_children ON subject (parent)
    WHERE parent IS NOT NULL;

-- The strip's numbers, precomputed per subject and year.
--
-- Not an optimisation reached for early. Measured: the eighteen hand-written
-- regexes answered in 0.5s, twenty-seven derived subjects in 3.7s, and the
-- same twenty-seven plus twelve sub-subjects in 163 SECONDS. A sub-subject is
-- counted inside its parent, so each child evaluates its own alternation AND
-- its parent's against every published title, and `~*` cannot use an index.
-- The page has to show meaningful content within a second.
--
-- The vocabulary changes when somebody runs `bin/subjects.py`. The front page
-- is read constantly. So the join happens at curation time and the page reads
-- 39 x 12 rows, which is the same trade `speaker_resolved` makes against
-- resolving four levels of speaker claim on every transcript request.
--
-- Rebuilt whole, never incrementally: a vocabulary edit can move any row in
-- any year, and a partial refresh would leave the strip disagreeing with the
-- terms that produced it, silently.
CREATE TABLE IF NOT EXISTS subject_year (
    slug      text NOT NULL REFERENCES subject(slug) ON DELETE CASCADE,
    year      text NOT NULL,
    items     integer NOT NULL DEFAULT 0,
    meetings  integer NOT NULL DEFAULT 0,
    decided   integer NOT NULL DEFAULT 0,
    continued integer NOT NULL DEFAULT 0,
    refused   integer NOT NULL DEFAULT 0,
    divided   integer NOT NULL DEFAULT 0,
    lines     integer NOT NULL DEFAULT 0,
    heard     integer NOT NULL DEFAULT 0,
    first     text,
    last      text,
    built_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (slug, year)
);

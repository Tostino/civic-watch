-- Schema for the Pasco meeting archive on PostgreSQL 17 + pgvector 0.8.
--
-- One database holds what used to be three stores: the SQLite catalog, the
-- FTS5 index, and a 257 MB passages.npy that had to be loaded whole into RAM
-- and matmul'd in full for every query. Vectors now live beside the rows they
-- belong to, with an HNSW index instead of a linear scan.
--
-- "end" is a reserved word in SQL and is quoted everywhere it appears. It is
-- not renamed, so every Python dict key that reads a row stays as it was.

CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ---------------------------------------------------------------- catalog
CREATE TABLE IF NOT EXISTS videos (
    id            text PRIMARY KEY,
    title         text NOT NULL,
    duration      double precision,
    -- meeting date parsed from the title (YYYY-MM-DD). Kept as text because
    -- retrieval compares it as a string against user-supplied since/until.
    upload_date   text,
    kind          text,
    source        text,
    downloaded    boolean NOT NULL DEFAULT false,
    diarized      boolean NOT NULL DEFAULT false,
    transcribed   boolean NOT NULL DEFAULT false,
    claimed_by    text,
    words         integer,
    speakers      integer,
    gap_seconds   double precision,
    error         text,
    updated_at    timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS videos_queue ON videos (downloaded, diarized, transcribed)
    WHERE error IS NULL;

CREATE TABLE IF NOT EXISTS utterances (
    video_id    text    NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
    idx         integer NOT NULL,
    start       double precision NOT NULL,
    "end"       double precision NOT NULL,
    speaker     text,
    -- What the archive PUBLISHES. Equal to text_raw until a redaction is
    -- applied, after which it is text_raw with the addresses replaced by a
    -- marker (bin/redact.py: republish). Everything derived comes from this
    -- column: tsv below, and passages with their BM25 postings and embeddings.
    text        text    NOT NULL,
    cluster     integer,
    local_label text,
    -- Keyword search for the research tab. Generated, so it can never drift
    -- from the text the way an explicitly-maintained FTS table could.
    tsv         tsvector GENERATED ALWAYS AS (to_tsvector('english', text)) STORED,
    PRIMARY KEY (video_id, idx)
);
-- The recogniser's own words, written once by db.index_video and never again.
-- A redaction removes an address from what is published without destroying
-- what was transcribed, so a revert recomputes rather than trusting a copy
-- taken at the time. Deliberately not indexed and deliberately not read by any
-- reader-facing query: it is the record, not the publication.
ALTER TABLE utterances ADD COLUMN IF NOT EXISTS text_raw text;
CREATE INDEX IF NOT EXISTS utt_video   ON utterances (video_id, start);
CREATE INDEX IF NOT EXISTS utt_cluster ON utterances (cluster);
CREATE INDEX IF NOT EXISTS utt_tsv     ON utterances USING gin (tsv);

-- ---------------------------------------------------------------- agenda
CREATE TABLE IF NOT EXISTS segments (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id     text    NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
    seq          integer NOT NULL,
    start_idx    integer NOT NULL,
    end_idx      integer NOT NULL,
    start        double precision NOT NULL,
    "end"        double precision NOT NULL,
    phase        text    NOT NULL,
    title        text,             -- for display; may contain unspoken words
    search_title text,             -- verified subset; safe to put in the index
    -- The PUBLISHED agenda code this stretch is, when the model matched it to
    -- one. Separate from `title` on purpose: the title is what was SAID and is
    -- grounded against the transcript, this is which county item it WAS and is
    -- checked against the published agenda. Reading a code out of the title
    -- string with a regex conflated the two and recovered 47%.
    code         text,
    continued    boolean NOT NULL DEFAULT false,
    UNIQUE (video_id, seq)
);
CREATE INDEX IF NOT EXISTS seg_span ON segments (video_id, start_idx);

-- ---------------------------------------------------------------- retrieval
CREATE TABLE IF NOT EXISTS passages (
    id          integer PRIMARY KEY,
    video_id    text    NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
    start       double precision NOT NULL,
    "end"       double precision NOT NULL,
    speaker     text,
    cluster     integer,
    text        text NOT NULL,     -- verbatim, for display
    search_text text,              -- carries the agenda subject; what is indexed
    segment_id  integer,
    phase       text,
    embedding   vector(1024)
);
CREATE INDEX IF NOT EXISTS pass_video ON passages (video_id, start);
CREATE INDEX IF NOT EXISTS pass_seg   ON passages (segment_id);
CREATE INDEX IF NOT EXISTS pass_phase ON passages (phase);

CREATE TABLE IF NOT EXISTS passage_keys (
    passage_id integer NOT NULL,
    kind       text NOT NULL,
    key        text NOT NULL
);
CREATE INDEX IF NOT EXISTS pk_key  ON passage_keys (kind, key);
CREATE INDEX IF NOT EXISTS pk_pass ON passage_keys (passage_id);

-- ---------------------------------------------------------------- speakers
CREATE TABLE IF NOT EXISTS speaker_identity (
    video_id    text NOT NULL,
    local_label text NOT NULL,
    cluster     integer,
    name        text,
    confidence  double precision,
    source      text,
    PRIMARY KEY (video_id, local_label)
);
CREATE INDEX IF NOT EXISTS si_cluster ON speaker_identity (cluster);

CREATE TABLE IF NOT EXISTS speaker_label (
    video_id    text NOT NULL,
    local_label text NOT NULL,
    name        text NOT NULL,
    note        text,
    labeled_at  timestamptz DEFAULT now(),
    PRIMARY KEY (video_id, local_label)
);

CREATE TABLE IF NOT EXISTS speaker_ignore (
    video_id    text NOT NULL,
    local_label text NOT NULL,
    reason      text,
    at          timestamptz DEFAULT now(),
    PRIMARY KEY (video_id, local_label)
);

-- The name a voice goes by IN A GIVEN MEETING.
-- ---------------------------------------------------------------- BM25
--
-- This cluster has no pg_search, and Postgres' own ts_rank_cd is not BM25 -
-- it has no real IDF and no document-length saturation, and this corpus is
-- full of proper nouns and case numbers where those two terms are exactly
-- what does the work. So BM25 is materialised: postings, document lengths,
-- and document frequencies, scored with the Okapi formula at query time.
--
-- Both sides go through to_tsvector('english', ...), so the analyzer that
-- builds the postings is the same one that parses the query. That is the
-- part most likely to be got wrong, and it is why neither side ever
-- tokenises by hand.
CREATE TABLE IF NOT EXISTS passage_terms (
    passage_id integer  NOT NULL,
    term       text     NOT NULL,
    tf         smallint NOT NULL
);
CREATE TABLE IF NOT EXISTS passage_len (
    passage_id integer PRIMARY KEY,
    len        integer NOT NULL
);
CREATE TABLE IF NOT EXISTS term_df (
    term text PRIMARY KEY,
    df   integer NOT NULL
);
CREATE TABLE IF NOT EXISTS bm25_stats (
    n_docs bigint NOT NULL,
    avgdl  double precision NOT NULL
);

-- Embedding cache, keyed on the exact string that was embedded. A re-index
-- after a segmentation pass changes only the passages whose item gained a
-- title; everything else is served from here instead of the GPU.
CREATE TABLE IF NOT EXISTS vec_cache (
    h text PRIMARY KEY,
    v vector(1024) NOT NULL
);

-- ================================================================ domain
-- The tables above model artifacts: a video file, a span of a video, a name
-- string. These model what the archive is actually about.

-- A meeting is the real-world event. It is NOT a video: roughly half of these
-- run as a morning and an afternoon recording on one continuous agenda, and a
-- day may also carry a workshop or budget hearing that is a separate meeting
-- sharing the date. Recordings whose order cannot be established (a dropped
-- stream restarted, an unlabelled session) become their own meeting rather
-- than being guessed into a sequence - see segment.day_groups().
CREATE TABLE IF NOT EXISTS meetings (
    id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date  text,                        -- YYYY-MM-DD, parsed from the title
    body  text,                        -- bcc | planning | mpo | workshop
    title text,
    UNIQUE (date, body, id)
);
CREATE INDEX IF NOT EXISTS meetings_date ON meetings (date DESC);

ALTER TABLE videos ADD COLUMN IF NOT EXISTS meeting_id  integer REFERENCES meetings(id);
ALTER TABLE videos ADD COLUMN IF NOT EXISTS session_seq integer;  -- 0=morning, 1=afternoon
CREATE INDEX IF NOT EXISTS videos_meeting ON videos (meeting_id, session_seq);

-- An agenda item is a thing the board took up. It belongs to a meeting, not to
-- a recording, so an item interrupted by lunch is ONE row here with two spans
-- below - which is what `segments.continued` was approximating with a boolean.
CREATE TABLE IF NOT EXISTS agenda_items (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id   integer NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
    seq          integer NOT NULL,
    phase        text    NOT NULL,
    title        text,
    search_title text,               -- verified subset; safe to index
    code         text,               -- R-58, PDE-260033 when one was spoken
    UNIQUE (meeting_id, seq)
);
CREATE INDEX IF NOT EXISTS agenda_code ON agenda_items (code) WHERE code IS NOT NULL;

-- Where an item physically occurs. One row per recording it appears in.
CREATE TABLE IF NOT EXISTS item_spans (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agenda_item_id integer NOT NULL REFERENCES agenda_items(id) ON DELETE CASCADE,
    video_id       text    NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
    part           integer NOT NULL DEFAULT 0,   -- 0 = where the item began
    start_idx      integer NOT NULL,
    end_idx        integer NOT NULL,
    start          double precision NOT NULL,
    "end"          double precision NOT NULL,
    UNIQUE (video_id, start_idx)
);
CREATE INDEX IF NOT EXISTS spans_item  ON item_spans (agenda_item_id, part);
CREATE INDEX IF NOT EXISTS spans_video ON item_spans (video_id, start_idx);

-- ================================================== authoritative source
-- Pasco publishes its agendas and minutes through CivicClerk. Those carry the
-- official structure - item numbers, titles, departments, case numbers, the
-- motion, mover, seconder and vote - which we were otherwise inferring from
-- 78%-precise voice matching over an ASR transcript.
--
-- Landed raw first, on purpose. The portal is someone else's system and its
-- shape will change; keeping the untouched payload means a parsing bug is
-- re-runnable from disk instead of re-scraped, and provenance for any derived
-- claim is a row away.
CREATE TABLE IF NOT EXISTS portal_events (
    id           integer PRIMARY KEY,      -- CivicClerk event id
    name         text,
    body         text,                     -- categoryName: BCC, Planning, MPO
    event_date   timestamptz,
    agenda_id    integer,
    has_agenda   boolean,
    meeting_id   integer REFERENCES meetings(id),   -- resolved later
    raw          jsonb NOT NULL,
    fetched_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS portal_events_date ON portal_events (event_date DESC);
CREATE INDEX IF NOT EXISTS portal_events_body ON portal_events (body);

CREATE TABLE IF NOT EXISTS portal_files (
    file_id      integer PRIMARY KEY,
    event_id     integer NOT NULL REFERENCES portal_events(id) ON DELETE CASCADE,
    kind         text,                     -- Agenda | Minutes | Agenda Packet
    name         text,
    published_at timestamptz,
    body_text    text,                     -- GetMeetingFileStream(plainText=true)
    chars        integer,
    fetched_at   timestamptz
);
CREATE INDEX IF NOT EXISTS portal_files_event ON portal_files (event_id, kind);
CREATE INDEX IF NOT EXISTS portal_files_todo  ON portal_files (kind)
    WHERE body_text IS NULL;

-- A case is the thing that recurs. An agenda number (C5, P79) is positional to

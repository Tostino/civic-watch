-- "has this come up before" a join rather than a search.
CREATE TABLE IF NOT EXISTS cases (
    id          text PRIMARY KEY,          -- normalised PREFIX-YY-SEQ
    prefix      text,                      -- PDE, PDD, CAO, CO, FAC, ...
    first_seen  date,
    last_seen   date,
    meetings    integer NOT NULL DEFAULT 0,
    bodies      integer NOT NULL DEFAULT 0
);


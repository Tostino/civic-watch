CREATE TABLE IF NOT EXISTS vec_cache (
    h text PRIMARY KEY,
    v vector(1024) NOT NULL
);

-- ================================================================ domain
-- The tables above model artifacts: a video file, a span of a video, a name
-- string. These model what the archive is actually about.

-- A meeting is the real-world event, NOT a video: roughly half run as a morning
-- and an afternoon recording on one agenda, and a day may carry a workshop that
-- is a separate meeting sharing the date. Recordings whose order cannot be
-- established become their own meeting rather than being guessed into one.
CREATE TABLE IF NOT EXISTS meetings (
    id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date  text,                        -- YYYY-MM-DD, parsed from the title
    body  text,                        -- bcc | planning | mpo | workshop
    title text,
    UNIQUE (date, body, id)
);
CREATE INDEX IF NOT EXISTS meetings_date ON meetings (date DESC);

ALTER TABLE videos ADD COLUMN IF NOT EXISTS meeting_id  integer REFERENCES meetings(id);
ALTER TABLE videos ADD COLUMN IF NOT EXISTS session_seq integer;  -- 0=morning, 1=afternoon
CREATE INDEX IF NOT EXISTS videos_meeting ON videos (meeting_id, session_seq);

-- An agenda item is a thing the board took up. It belongs to a meeting, not to
-- a recording, so an item interrupted by lunch is ONE row here with two spans
-- below - which is what `segments.continued` was approximating with a boolean.
CREATE TABLE IF NOT EXISTS agenda_items (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id   integer NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
    seq          integer NOT NULL,
    phase        text    NOT NULL,
    title        text,
    search_title text,               -- verified subset; safe to index
    code         text,               -- R-58, PDE-260033 when one was spoken
    UNIQUE (meeting_id, seq)
);
CREATE INDEX IF NOT EXISTS agenda_code ON agenda_items (code) WHERE code IS NOT NULL;

-- Where an item physically occurs. One row per recording it appears in.
CREATE TABLE IF NOT EXISTS item_spans (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agenda_item_id integer NOT NULL REFERENCES agenda_items(id) ON DELETE CASCADE,
    video_id       text    NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
    part           integer NOT NULL DEFAULT 0,   -- 0 = where the item began
    start_idx      integer NOT NULL,
    end_idx        integer NOT NULL,
    start          double precision NOT NULL,
    "end"          double precision NOT NULL,
    UNIQUE (video_id, start_idx)
);
CREATE INDEX IF NOT EXISTS spans_item  ON item_spans (agenda_item_id, part);
CREATE INDEX IF NOT EXISTS spans_video ON item_spans (video_id, start_idx);

